interface I18nValue {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  t: (english: string) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function translate(english: string, language: AppLanguage): string {
  return language === "es" ? spanish[english] ?? english : english;
}

function initialLanguage(): AppLanguage {
  try {
    return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === "es" ? "es" : "en";
  } catch {
    return "en";
  }
}

export function I18nProvider({ children }: { children: ReactNode }): JSX.Element {
  const [language, updateLanguage] = useState<AppLanguage>(initialLanguage);
  const setLanguage = useCallback((next: AppLanguage) => {
    updateLanguage(next);
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, next);
    } catch {
      // Storage can be unavailable in privacy-restricted browser contexts.
    }
  }, []);
  const value = useMemo<I18nValue>(
    () => ({ language, setLanguage, t: (english) => translate(english, language) }),
    [language, setLanguage],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("I18nProvider is required");
  }
  return value;
}

const originalText = new WeakMap<Text, string>();
const originalAttributes = new WeakMap<Element, Map<string, string>>();
const translatedAttributes = ["title", "placeholder", "aria-label"] as const;

function localizeTree(root: HTMLElement, language: AppLanguage): void {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let current = walker.nextNode();
  while (current) {
    const node = current as Text;
    const value = node.nodeValue ?? "";
    const match = value.match(/^(\s*)(.*?)(\s*)$/s);
    const trimmed = match?.[2] ?? value;
    let source = originalText.get(node);
    if (!source || (value !== source && value !== translate(source, "es"))) {
      source = trimmed;
      originalText.set(node, source);
    }
    const localized = translate(source, language);
    const next = `${match?.[1] ?? ""}${localized}${match?.[3] ?? ""}`;
    if (node.nodeValue !== next) node.nodeValue = next;
    current = walker.nextNode();
  }
  for (const element of root.querySelectorAll("[title], [placeholder], [aria-label]")) {
    let sources = originalAttributes.get(element);
    if (!sources) {
      sources = new Map<string, string>();
      originalAttributes.set(element, sources);
    }
    for (const attribute of translatedAttributes) {
      const currentValue = element.getAttribute(attribute);
      if (!currentValue) continue;
      const stored = sources.get(attribute);
      if (!stored || (currentValue !== stored && currentValue !== translate(stored, "es"))) {
        sources.set(attribute, currentValue);
      }
      const localized = translate(sources.get(attribute) ?? currentValue, language);
      if (currentValue !== localized) element.setAttribute(attribute, localized);
    }
  }
}

export function LocalizedSurface({ children }: { children: ReactNode }): JSX.Element {
  const { language } = useI18n();
  const ref = useRef<HTMLDivElement>(null);
  useLayoutEffect(() => {
    const root = ref.current;
    if (!root) return;
    let applying = false;
    const apply = (): void => {
      if (applying) return;
      applying = true;
      localizeTree(root, language);
      applying = false;
    };
    apply();
    const observer = new MutationObserver(() => apply());
    observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: [...translatedAttributes] });
    return () => observer.disconnect();
  }, [language]);
  return <div ref={ref} className="contents" lang={language}>{children}</div>;
}
